#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_blank_for_unknown() {
        let g = glyph_bits('\u{1F600}'); // emoji — not in font
        assert_eq!(g, [0u8; 8]);
    }

    #[test]
    fn glyph_space_is_blank() {
        assert_eq!(glyph_bits(' '), [0u8; 8]);
    }

    #[test]
    fn glyph_letters_nonblank() {
        for c in 'A'..='Z' {
            let g = glyph_bits(c);
            assert!(g.iter().any(|&r| r != 0), "glyph {c} was blank");
        }
        for c in 'a'..='z' {
            let g = glyph_bits(c);
            assert!(g.iter().any(|&r| r != 0), "glyph {c} was blank");
        }
        for c in '0'..='9' {
            let g = glyph_bits(c);
            assert!(g.iter().any(|&r| r != 0), "glyph {c} was blank");
        }
    }
}
